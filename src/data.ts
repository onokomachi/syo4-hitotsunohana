  yousu:   { label: 'ようす・できごと', desc: '人物のしたことや様子を、本文から見つけられる' },
  kimochi: { label: '気持ちとわけ', desc: '人物の気持ちと、そのわけを本文の言葉から読み取れる' },
  henka:   { label: 'うつりかわり・情景', desc: '場面のうつりかわりと結びつけて、気持ちの変化や情景を読み取れる' },
